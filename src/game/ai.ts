// Клиент его не знает и не может показать: здесь нет ни ключа, ни его части.
// Если сервер недоступен (соло-режим, нет сети), отвечает встроенная база
// знаний — тот же текст, что знает модель, только без генерации.
import { getServerUrl } from './net';

export interface AiMsg { role: 'user' | 'assistant'; content: string }
export interface AiAnswer { text: string; off?: boolean }

/** адрес ассистента: тот же хост, что у игрового сервера, только http(s) */
export function aiEndpoint(): string {
  const env = (import.meta.env as Record<string, string | undefined> | undefined)?.VITE_AI_URL;
  if (env && /^https?:\/\//i.test(env)) return env.replace(/\/+$/, '') + '/ai/chat';
  let ws = '';
  try { ws = getServerUrl(); } catch { ws = ''; }
  if (!ws) return '';
  return ws.replace(/^ws/i, 'http').replace(/\/+$/, '') + '/ai/chat';
}

/** вопрос к модели через сервер; null — сервер молчит, отвечаем сами */
export async function askGimpt(history: AiMsg[], timeoutMs = 22_000): Promise<AiAnswer | null> {
  const url = aiEndpoint();
  if (!url) return null;
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), timeoutMs);
  try {
    const r = await fetch(url, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ messages: history.slice(-8) }),
      signal: ctl.signal,
    });
    const j = await r.json() as { ok?: boolean; text?: string };
    if (j && j.ok && typeof j.text === 'string' && j.text.trim()) return { text: j.text.trim() };
    if (j && typeof j.text === 'string' && j.text.trim()) return { text: j.text.trim(), off: true };
    return null;
  } catch { return null; } finally { clearTimeout(timer); }
}


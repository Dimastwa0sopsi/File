/** подсказка «что делать дальше» по текущему состоянию игрока */
export function gimptAdvice(ctx: AiContext): string {
  if (ctx.wanted >= 2) return 'Сейчас главное — сбросить розыск: уйдите из зоны видимости полиции и не нарушайте полминуты.';
  if (ctx.water < 25) return 'Вода почти на нуле. Ближайший колодец во дворе усадьбы или кран в оранжерее: подойдите и нажмите E.';
  if (ctx.food < 25) return 'Еда на нуле: магазин в планшете (Вкусно Доставка / Кофейня) выдаст заказ рядом с вами.';
  if (ctx.energy < 20) return 'Вы вымотались. Выспитесь в своём жилье или выпейте кофе в кофейне.';
  if (!ctx.job && ctx.money < 5000) return 'Свободна работа? Откройте «Работы» в планшете — такси или доставка дадут деньги за пару минут.';
  if (ctx.vehicles === 0 && ctx.money > 12000) return 'На счету достаточно на первое авто — «Автобазар» в планшете, и город станет заметно быстрее.';
  if (ctx.homes === 0 && ctx.money > 60000) return 'Можно взять квартиру: «Недвижимость» → квартира. Своё жильё нужно для отдыха и хранения.';
  if (ctx.night) return 'Ночь: включите фары (L) и загляните к бассейну — подсветка воды выглядит отлично.';
  return 'Всё в порядке. Возьмите ежедневное задание или прокатитесь по чекпоинтам (K) — и деньги, и рекорд.';
}

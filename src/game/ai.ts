const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е');

/** ответ из локальной базы: ищем по ключевым словам, учитывая состояние игрока */
export function gimptLocalAnswer(q: string, ctx?: AiContext): string {
  const t = norm(q);
  let best: Article | null = null; let bestScore = 0;
  for (const a of KB) {
    let score = 0;
    for (const k of a.keys) if (t.includes(norm(k))) score += k.length;
    if (score > bestScore) { bestScore = score; best = a; }
  }
  if (!best) {
    if (t.includes('привет') || t.includes('здравств') || t.includes('хай')) return 'Привет! Я ChatGIMPT — помогу разобраться в игре. Спросите про деньги, транспорт, розыск, бассейны, оранжерею, гонки или ремонт. Или нажмите «Обучение».';
    if (t.includes('спасибо') || t.includes('благодар')) return 'Всегда пожалуйста! Если что-то ещё непонятно — спрашивайте.';
    return 'Пока отвечаю по памяти игры, без связи с моделью. Спросите про деньги, транспорт, розыск, бассейны, оранжерею, колодцы, гонки, задания или внешность — расскажу по шагам.';
  }
  let extra = '';
  if (ctx) {
    if (best.keys.includes('начать')) {
      const steps: string[] = [];
      if (!ctx.job) steps.push(`работы пока нет — откройте «Работы» в планшете`);
      if (ctx.money < 3000) steps.push(`на счету ${$(ctx.money)} — начните с такси или доставки`);
      if (ctx.vehicles === 0) steps.push('своего транспорта нет — автобазар и первое авто окупятся быстро');
      if (ctx.water < 40 || ctx.food < 40) steps.push('низкие еда/вода — купите воду и еду в магазине');
      if (ctx.wanted > 0) steps.push(`у вас ${ctx.wanted}★ розыска — лучше сначала залечь на дно`);
      extra = steps.length ? '\n\nСейчас именно вам: ' + steps.map((x) => '• ' + x).join('\n') : '\n\nУ вас всё ровно: можно браться за крупные цели — жильё и бизнес.';
    } else if (best.keys.includes('деньг')) extra = `\n\nНа счету ${$(ctx.money)}${ctx.homes ? `, объектов недвижимости: ${ctx.homes}` : ''}.`;
  }
  return `${best.title}. ${best.body}${extra}`;
}

